// Disposable browser test for independent notebooks, dual modes, backup and legacy data.
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const BASE='http://127.0.0.1:8157/';
const server=spawn(process.execPath,['tests/serve-with-headers.cjs','.','8157'],{stdio:['ignore','pipe','pipe']});
(async()=>{
 let browser;
 try{
  await new Promise((resolve,reject)=>{let t=setTimeout(()=>reject(Error('Server start timeout')),10000);server.stdout.on('data',d=>{if(d.toString().includes('up')){clearTimeout(t);resolve()}});server.once('error',reject)});
  browser=await chromium.launch({headless:true});
  const ctx=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,acceptDownloads:true});
  await ctx.route(/supabase\.co/,r=>r.abort());
  await ctx.addInitScript(()=>{
   localStorage.setItem('nv-write-v1',JSON.stringify({topics:[{id:'legacy-1',title:'Bài viết cũ',content:'Nội dung cũ giữ nguyên',tag:'Chưa phân loại',status:'draft',created_at:'2026-11-20T00:00:00Z',updated_at:'2026-11-20T00:00:00Z',deleted:false}],logs:{},settings:{},syncQueue:[]}));
  });
  const page=await ctx.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(BASE,{waitUntil:'domcontentloaded'});
  await page.locator('[data-tab="topics"]').click();
  assert.equal(await page.locator('#nvTopicResults [data-open]').count(),1,'legacy topic remains visible');
  await page.locator('[data-nb="goto-notebooks"]').click();
  await page.waitForSelector('[data-nb="new"]');
  const nativeDialogs=[];
  page.on('dialog',async d=>{nativeDialogs.push(d.message());await d.dismiss()});
  await page.locator('[data-nb="new"]').click();
  await page.waitForSelector('.nv-book-choice-sheet');
  assert.equal(await page.locator('.nv-book-choice-card').count(),3,'three notebook types visible');
  assert.equal(await page.locator('#nvBookBody').count(),0,'picker does not open editor before choice');
  assert.equal(await page.locator('.nv-book-choice-sheet').getAttribute('aria-modal'),'true','accessible modal picker');
  assert.match(await page.locator('#nvBookNewTitle').inputValue(),/^Vở luyện viết/,'a title is filled in');
  await page.locator('#nvBookNewTitle').fill('Nhật ký học viết');
  await page.locator('#nvBookCreateForm button[type="submit"]').click();
  await page.waitForSelector('#nvBookBody');
  const editorBox=await page.locator('#nvBookBody').boundingBox();
  assert(editorBox.y<=178,'compact mobile header leaves room for content: '+editorBox.y);
  const toolbarBox=await page.locator('.nv-book-top').boundingBox();
  assert(toolbarBox.height<=48,'top toolbar stays compact');
  await page.locator('.nv-book-menu summary').click();
  assert.match(await page.locator('.nv-book-menu').innerText(),/Luyện viết · XP · 1 phần/);
  await page.locator('.nv-book-menu summary').click();
  assert.equal(nativeDialogs.length,0,'no native browser prompts for creation');
  assert.equal(await page.locator('[data-nb="contents"]').count(),1,'new book opens in editor');
  assert.equal(await page.locator('#nvBookTitle').inputValue(),'Nhật ký học viết','custom title survives creation');
  await page.getByRole('button',{name:'Đổi tên vở',exact:true}).click();
  assert.equal(await page.locator('#nvBookTitle').evaluate(el=>document.activeElement===el),true,'rename button focuses title');
  await page.locator('#nvBookTitle').fill('Sổ luyện viết mỗi ngày');
  await page.locator('#nvBookTitle').evaluate(el=>el.blur());
  assert.equal(await page.evaluate(()=>window.nvNotebookUI.exportData()[0].title),'Sổ luyện viết mỗi ngày','inline title edit saves in notebook state');
  assert.equal(await page.locator('[data-nb="scroll"]').getAttribute('aria-pressed'),'true','continuous mode is default');
  await page.locator('#nvBookBody').fill('Tôi viết mỗi ngày để ghi lại những ý tưởng mới và học hỏi.');
  await page.locator('#nvBookBody').evaluate(el=>{
   const selection=window.getSelection(),range=document.createRange();
   range.selectNodeContents(el);selection.removeAllRanges();selection.addRange(range);
  });
  await page.locator('[data-nb-format="bold"]').click();
  assert((await page.locator('#nvBookBody').innerHTML()).match(/<(b|strong)>/i),'Write-like bold formatting works');
  assert((await page.locator('#nvBookBody').innerText()).includes('Tôi viết mỗi ngày'),'formatting does not lose text');
  await page.locator('#nvBookBody').evaluate(el=>el.blur());
  await page.waitForTimeout(800);
  const result=await page.evaluate(()=>({article:JSON.parse(localStorage.getItem('nv-write-v1')).topics[0],xp:JSON.parse(localStorage.getItem('nv-write-xp-v1')).total,books:window.nvNotebookUI.exportData()}));
  assert.equal(result.article.content,'Nội dung cũ giữ nguyên','legacy content unchanged');
  assert.equal(result.books.length,1,'one notebook saved in IndexedDB');
  assert.equal(result.books[0].parts[0].text,'Tôi viết mỗi ngày để ghi lại những ý tưởng mới và học hỏi.');
  assert.equal(result.books[0].title,'Sổ luyện viết mỗi ngày','title persisted');
  assert(result.books[0].parts[0].richHtml.includes('<b>')||result.books[0].parts[0].richHtml.includes('<strong>'),'rich formatting persisted in notebook record');
  assert(result.xp>0,'new words in writing-type notebook gain XP');
  await page.locator('[data-nb="flip"]').click();
  assert.equal(await page.locator('[data-nb="flip"]').getAttribute('aria-pressed'),'true','flip mode selected');
  assert((await page.locator('#nvBookBody').innerText()).includes('Tôi viết mỗi ngày'),'same content in flip mode');
  assert((await page.locator('#nvBookBody').innerHTML()).match(/<(b|strong)>/i),'flip mode preserves formatting');
  await page.locator('[data-nb="scroll"]').click();
  assert((await page.locator('#nvBookBody').innerText()).includes('Tôi viết mỗi ngày'),'same content when switching back');
  await page.locator('[data-nb="back"]').click();
  await page.waitForTimeout(550);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('[data-tab="topics"]').click();
  await page.locator('[data-nb="goto-notebooks"]').click();
  await page.waitForTimeout(1000);
  const diag=await page.evaluate(async()=>{
    const open=await new Promise((resolve,reject)=>{const q=indexedDB.open('nv-write-notebooks-v1',1);q.onsuccess=()=>resolve(q.result);q.onerror=()=>reject(q.error)});
    const saved=await new Promise((resolve,reject)=>{const q=open.transaction('books','readonly').objectStore('books').getAll();q.onsuccess=()=>resolve(q.result);q.onerror=()=>reject(q.error)});
    return {saved:saved.map(x=>({id:x.id,title:x.title,deleted:x.deleted,archived:x.archived})),memory:window.nvNotebookUI.exportData(),rendered:document.querySelector('#content')?.innerText.slice(0,700),tab:(document.querySelector('#tabs .active')?.textContent)};
  });
  console.log('NOTEBOOK PERSISTENCE AFTER RELOAD:',JSON.stringify(diag));
  assert.equal(await page.locator('[data-nb="open"]').count(),1,'Notebook should be visible after reload '+JSON.stringify(diag));
  const cover=page.getByRole('button',{name:'Mở quyển Sổ luyện viết mỗi ngày'});
  const size=await cover.boundingBox();
  assert(size.height>=165&&size.width>=150,'library displays a large tappable notebook cover on mobile');
  assert.equal(await page.locator('[data-nb="goto-notebooks"]').getAttribute('aria-current'),'page');
  await page.locator('[data-nb="open"]').first().click();
  assert((await page.locator('#nvBookBody').innerText()).includes('Tôi viết mỗi ngày'),'notebook survives page reload');
  assert.equal(await page.locator('#nvBookTitle').inputValue(),'Sổ luyện viết mỗi ngày','rename survives reload');
  assert((await page.locator('#nvBookBody').innerHTML()).match(/<(b|strong)>/i),'rich text survives reload');
  const snapshot=await page.evaluate(()=>({legacy:JSON.parse(localStorage.getItem('nv-write-v1')).topics,notebooks:window.nvNotebookUI.exportData()}));
  assert.equal(snapshot.legacy.length,1);
  assert.equal(snapshot.notebooks.length,1);
  await page.locator('[data-nb="back"]').click();
  await page.locator('[data-nb="new"]').click();
  await page.locator('[data-nb="cancel-new"]').click();
  assert.equal(await page.locator('.nv-book-choice-sheet').count(),0,'cancel closes picker without creating a book');
  assert.equal(await page.locator('[data-nb="open"]').count(),1,'cancel leaves the library unchanged');
  await page.locator('[data-nb="new"]').click();
  await page.locator('[data-nb="choose-knowledge"]').click();
  assert.equal(await page.locator('#nvBookNewTitle').inputValue(),'Vở kiến thức 1');
  await page.locator('#nvBookCreateForm button[type="submit"]').click();
  await page.waitForSelector('#nvBookBody');
  assert.equal(await page.evaluate(()=>window.nvNotebookUI.exportData().find(x=>x.kind==='knowledge')?.title),'Vở kiến thức 1','knowledge notebook suggested name');
  await page.locator('[data-nb="back"]').click();
  await page.locator('[data-nb="new"]').click();
  await page.locator('[data-nb="choose-free"]').click();
  await page.locator('#nvBookCreateForm button[type="submit"]').click();
  await page.waitForSelector('#nvBookBody');
  assert.equal(await page.evaluate(()=>window.nvNotebookUI.exportData().find(x=>x.kind==='free')?.title),'Vở tự do 1','free notebook suggested name');
  assert.equal(await page.evaluate(()=>window.nvNotebookUI.exportData().length),3,'all kinds save independently');
  await page.locator('.nv-book-write-options [data-nb="add-part"]').click();
  await page.locator('#nvBookPartName').fill('Chương hai');
  await page.getByRole('button',{name:'Tạo và viết'}).click();
  const body=page.locator('#nvBookBody');
  assert.equal(await body.evaluate(el=>document.activeElement===el),true,'new section is ready to type');
  assert.equal(await page.locator('#nvBookPartTitle').inputValue(),'Chương hai');
  await body.fill(Array.from({length:100},(_,i)=>'Đoạn '+(i+1)+' có nội dung dài để kiểm tra vị trí khi đổi chế độ.').join('\n'));
  await body.evaluate(el=>{
   el.blur();
   window.getSelection().removeAllRanges();
   el.scrollTop=el.scrollHeight/2;
  });
  await page.locator('[data-nb="flip"]').click();
  const count=page.locator('#nvBookPageCount');
  let [current,total]=(await count.innerText()).split(' / ').map(Number);
  assert(current>1&&current<total,'switch to flip stays near the middle of a long section');
  await page.locator('[data-nb="next"]').click();
  await page.waitForFunction(n=>Number(document.querySelector('#nvBookPageCount').textContent.split(' / ')[0])>n,current);
  await page.locator('[data-nb="scroll"]').click();
  assert(await body.evaluate(el=>el.scrollTop>0),'switch back keeps a nonzero scroll position');
  await page.locator('[data-nb="contents"]').click();
  assert.equal(await page.locator('#nvBookContents button[aria-current=true]').innerText(),'Chương hai');
  await page.getByRole('button',{name:'Trang đầu tiên',exact:true}).click();
  assert.equal(await page.locator('#nvBookPartTitle').inputValue(),'Trang đầu tiên');
  await page.locator('[data-nb="contents"]').click();
  await page.getByRole('button',{name:'Chương hai',exact:true}).click();
  await page.locator('[data-nb="back"]').click();
  assert.match(await page.locator('.nv-book-grid').innerText(),/Chương hai/);
  await page.locator('[data-tab="home"]').click();
  await page.locator('#nvBookContinue').click();
  assert.equal(await page.locator('#nvBookPartTitle').inputValue(),'Chương hai','Continue resumes last section');
  assert.match(await page.locator('#nvBookStatus').innerText(),/lưu/i);
  assert.equal(nativeDialogs.length,0,'no browser prompts at any new-book step');
  assert.deepEqual(errors,[],'no browser errors');
  console.log('PASS: notebook titles, contents, add section, continue, mode position, reload, XP and legacy isolation');
  await ctx.close();
 }catch(e){console.error(e.stack||e);process.exitCode=1}
 finally{await browser?.close();server.kill()}
})();